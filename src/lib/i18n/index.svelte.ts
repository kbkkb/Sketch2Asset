const dictionaries: Record<LocaleCode, typeof zhCN> = {
  'zh-CN': zhCN,
  en
};

export type MessageKey = keyof typeof zhCN;

class I18nStore {
  locale = $state<LocaleCode>('zh-CN');

  t(key: MessageKey): string {
    const dict = dictionaries[this.locale] ?? zhCN;
    return dict[key] ?? zhCN[key] ?? key;
  }

  mattingModelName(id: string, fallback: string): string {
    const item = MATTING_MODEL_I18N[id];
    if (!item) return fallback;
    return this.locale === 'en' ? item.enName : item.zhName;
  }

  mattingModelDesc(id: string, fallback: string): string {
    const item = MATTING_MODEL_I18N[id];
    if (!item) return fallback;
    return this.locale === 'en' ? item.enDesc : item.zhDesc;
  }

  setLocale(code: LocaleCode) {
    if (dictionaries[code]) {
      this.locale = code;
    }
  }

  toggle() {
    this.locale = this.locale === 'zh-CN' ? 'en' : 'zh-CN';
  }
}

export const i18n = new I18nStore();
export const t = (key: MessageKey) => i18n.t(key);
